@bot.message_handler(
    func=lambda message: True,
    content_types=["text"]
)
def handle_subject_search(message):

    text = message.text.strip().lower()

    # Шукаємо точний збіг
    subject_name = ALIASES.get(text)

    # Якщо точного збігу немає —
    # шукаємо слово всередині повідомлення
    if not subject_name:

        for alias, subject in ALIASES.items():

            if alias in text:

                subject_name = subject
                break

    # Якщо предмет знайдено
    if subject_name:

        info_text, markup = get_subject_info(
            subject_name
        )

        if info_text:

            bot.send_message(
                message.chat.id,
                info_text,
                parse_mode="Markdown",
                reply_markup=markup
            )

            return

